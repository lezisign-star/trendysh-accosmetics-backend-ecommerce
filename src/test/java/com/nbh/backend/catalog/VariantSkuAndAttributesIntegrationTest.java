package com.nbh.backend.catalog;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.nbh.backend.common.security.JwtService;
import com.nbh.backend.staff.repository.StaffUserRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;
import org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder;

import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;

/**
 * Two Phase-C additions to the product editor's API: a SKU is auto-generated (category-prefixed,
 * sequential) when the caller omits one, and a variant's selected attribute values (Color: Red,
 * swatch #C0392B) now round-trip back through {@code ProductVariantDto} instead of only ever being
 * write-only.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
class VariantSkuAndAttributesIntegrationTest {

    @Autowired private MockMvc mvc;
    @Autowired private ObjectMapper json;
    @Autowired private JwtService jwtService;
    @Autowired private StaffUserRepository staffUsers;

    private String token;

    @BeforeEach
    void signInAsSuperAdmin() {
        var admin = staffUsers.findAll().stream()
                .filter(u -> u.getStaffRole() != null && "SUPER_ADMIN".equals(u.getStaffRole().getName()))
                .findFirst().orElseThrow();
        token = jwtService.generateAccessToken(admin);
    }

    private static String unique(String base) {
        return base + " " + UUID.randomUUID().toString().substring(0, 8);
    }

    private JsonNode ok(MockHttpServletRequestBuilder request, String body) throws Exception {
        request.header("Authorization", "Bearer " + token);
        if (body != null) request.contentType(MediaType.APPLICATION_JSON).content(body);
        MvcResult result = mvc.perform(request).andReturn();
        assertThat(result.getResponse().getStatus()).as(result.getResponse().getContentAsString()).isEqualTo(200);
        String content = result.getResponse().getContentAsString();
        return content.isBlank() ? null : json.readTree(content);
    }

    @Test
    void aVariantCreatedWithoutASkuGetsOneAutoGeneratedFromItsCategory() throws Exception {
        String categoryId = ok(post("/api/v1/categories"), "{\"name\":\"" + unique("Lashes") + "\"}")
                .get("id").asText();
        String body = "{\"name\":\"" + unique("Mink lashes") + "\",\"categoryId\":\"" + categoryId + "\","
                + "\"variants\":[{\"variantName\":\"Default\",\"sellingPrice\":\"500\",\"vatExempt\":false}]}";

        JsonNode product = ok(post("/api/v1/products"), body);
        String sku = product.get("variants").get(0).get("sku").asText();

        assertThat(sku).matches("LASH-\\d{6}");
    }

    @Test
    void twoAutoGeneratedSkusInARowAreDifferent() throws Exception {
        String body = "{\"name\":\"" + unique("Plain product") + "\","
                + "\"variants\":[{\"variantName\":\"Default\",\"sellingPrice\":\"500\",\"vatExempt\":false}]}";

        String sku1 = ok(post("/api/v1/products"), body).get("variants").get(0).get("sku").asText();
        String sku2 = ok(post("/api/v1/products"), body).get("variants").get(0).get("sku").asText();

        assertThat(sku1).isNotEqualTo(sku2);
        assertThat(sku1).matches("SKU-\\d{6}"); // no category on this one -> generic prefix
    }

    @Test
    void anExplicitSkuIsHonoredInstead() throws Exception {
        String explicit = "HAND-PICKED-" + UUID.randomUUID().toString().substring(0, 6).toUpperCase();
        String body = "{\"name\":\"" + unique("Custom SKU product") + "\","
                + "\"variants\":[{\"sku\":\"" + explicit + "\",\"variantName\":\"Default\","
                + "\"sellingPrice\":\"500\",\"vatExempt\":false}]}";

        String sku = ok(post("/api/v1/products"), body).get("variants").get(0).get("sku").asText();
        assertThat(sku).isEqualTo(explicit);
    }

    @Test
    void aVariantsSelectedAttributeValuesRoundTripThroughTheAdminDto() throws Exception {
        String attrCode = "shade-" + UUID.randomUUID().toString().substring(0, 8);
        JsonNode attribute = ok(post("/api/v1/attributes"),
                "{\"code\":\"" + attrCode + "\",\"name\":\"Shade\",\"displayType\":\"SWATCH\"}");
        String attributeId = attribute.get("id").asText();
        JsonNode value = ok(post("/api/v1/attributes/" + attributeId + "/values"),
                "{\"value\":\"crimson\",\"displayValue\":\"Crimson\",\"swatchHex\":\"#C0392B\"}");
        String valueId = value.get("id").asText();

        String body = "{\"name\":\"" + unique("Lipstick") + "\","
                + "\"variants\":[{\"variantName\":\"Crimson\",\"sellingPrice\":\"500\",\"vatExempt\":false,"
                + "\"attributeValueIds\":[\"" + valueId + "\"]}]}";

        JsonNode variant = ok(post("/api/v1/products"), body).get("variants").get(0);
        JsonNode attrs = variant.get("attributes");

        assertThat(attrs).hasSize(1);
        assertThat(attrs.get(0).get("attributeCode").asText()).isEqualTo(attrCode);
        assertThat(attrs.get(0).get("value").asText()).isEqualTo("crimson");
        assertThat(attrs.get(0).get("displayValue").asText()).isEqualTo("Crimson");
        assertThat(attrs.get(0).get("swatchHex").asText()).isEqualTo("#C0392B");
    }
}
